#!/usr/bin/env python3
"""Render a binary-only Homebrew formula from the latest stable fork release."""

import json
import os
from pathlib import Path
import re
import urllib.error
import urllib.request

REPOSITORY = "Caracolaracol/tuxedo-task"
API_URL = f"https://api.github.com/repos/{REPOSITORY}/releases/latest"
TARGETS = (
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "aarch64-unknown-linux-gnu",
    "x86_64-unknown-linux-gnu",
)


def fetch(url):
    headers = {"User-Agent": "tuxedotask-homebrew-updater/1.0"}
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if url.startswith("https://api.github.com/") and token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read(1024 * 1024).decode("utf-8")
    except urllib.error.HTTPError as error:
        # Installation tokens can be restricted to the tap repository. The
        # application release is public, so retry its metadata anonymously.
        if error.code in (403, 404) and "Authorization" in headers:
            del headers["Authorization"]
            with urllib.request.urlopen(
                urllib.request.Request(url, headers=headers), timeout=30
            ) as response:
                return response.read(1024 * 1024).decode("utf-8")
        raise


def archive_name(tag, target):
    return f"tuxedo-task-{tag}-{target}.tar.gz"


def release_url(tag, filename):
    return f"https://github.com/{REPOSITORY}/releases/download/{tag}/{filename}"


def collect_checksums(release, download=fetch):
    tag = release.get("tag_name", "")
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", tag):
        raise ValueError(f"Unexpected version tag: {tag!r}")
    if release.get("draft") or release.get("prerelease"):
        raise ValueError("Only public stable releases may update the formula")
    assets = {asset["name"]: asset for asset in release.get("assets", [])}
    checksums = {}
    for target in TARGETS:
        filename = archive_name(tag, target)
        for name in (filename, f"{filename}.sha256"):
            asset = assets.get(name)
            if asset is None or asset.get("browser_download_url") != release_url(tag, name):
                raise ValueError(f"Missing or unexpected asset: {name}")
        words = download(release_url(tag, f"{filename}.sha256")).strip().split()
        if len(words) != 2 or words[1].lstrip("*") != filename:
            raise ValueError(f"Unexpected checksum filename: {filename}")
        sha = words[0].lower()
        if not re.fullmatch(r"[0-9a-f]{64}", sha):
            raise ValueError(f"Invalid SHA-256 for {filename}")
        checksums[target] = sha
    return tag, checksums


def render_formula(tag, checksums):
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", tag):
        raise ValueError("Invalid formula version")
    if set(checksums) != set(TARGETS) or any(
        not re.fullmatch(r"[0-9a-f]{64}", value) for value in checksums.values()
    ):
        raise ValueError("A valid checksum for every target is required")
    version = tag[1:]
    major, minor, _ = map(int, version.split("."))
    # The legacy CalVer line is numerically higher than 1.x. Homebrew's epoch
    # must stay 1 for every SemVer release, not just the transition to 1.0.0.
    is_calver = 2000 <= major <= 2999 and 1 <= minor <= 12
    scheme_line = "" if is_calver else "\n  version_scheme 1"
    blocks = []
    for os_name, targets in (("macos", TARGETS[:2]), ("linux", TARGETS[2:])):
        lines = [f"  on_{os_name} do"]
        if os_name == "macos":
            lines.append("    depends_on macos: :monterey")
            lines.append("")
        for architecture, target in zip(("arm", "intel"), targets):
            lines.extend([
                f"    on_{architecture} do",
                f'      url "{release_url(tag, archive_name(tag, target))}"',
                f'      sha256 "{checksums[target]}"',
                "    end",
            ])
        lines.append("  end")
        blocks.append("\n".join(lines))
    return f'''# Generated by scripts/update_formula.py from published release checksums.
class Tuxedotask < Formula
  desc "Keyboard-driven todo.txt TUI with nested subtasks"
  homepage "https://github.com/{REPOSITORY}"
  version "{version}"{scheme_line}
  license "MIT"

  conflicts_with "tuxedo", because: "both provide the tuxedo command"

{chr(10).join(blocks)}

  def install
    bin.install "tuxedo"
    bin.install_symlink "tuxedo" => "tuxedotask"
  end

  def caveats
    <<~EOS
      Both tuxedo and tuxedotask start Tuxedo Task.
      Existing tasks and ~/.config/tuxedo configuration stay unchanged.
      If a Cargo/manual copy exists, check PATH with: command -v tuxedo
    EOS
  end

  test do
    assert_equal {0 if is_calver else 1}, version_scheme
    expected = "Tuxedo Task #{{version}}"
    assert_match expected, shell_output("#{{bin}}/tuxedo --version")
    assert_equal shell_output("#{{bin}}/tuxedo --version"),
                 shell_output("#{{bin}}/tuxedotask --version")
    assert_match "brew upgrade caracolaracol/tap/tuxedotask",
                 shell_output("#{{bin}}/tuxedotask update")

    ENV["TODO_FILE"] = (testpath/"todo.txt").to_s
    ENV["DONE_FILE"] = (testpath/"done.txt").to_s
    ENV["XDG_CONFIG_HOME"] = (testpath/"config").to_s
    ENV["XDG_CACHE_HOME"] = (testpath/"cache").to_s
    ENV["TUXEDO_NO_UPDATE_CHECK"] = "1"
    system bin/"tuxedo", "add", "Verify Homebrew +test @local"
    assert_match "Verify Homebrew", shell_output("#{{bin}}/tuxedotask ls")
    system bin/"tuxedotask", "do", "1"
    system bin/"tuxedo", "archive"
    assert_match "Verify Homebrew", (testpath/"done.txt").read
  end
end
'''


def main():
    release = json.loads(fetch(API_URL))
    tag, checksums = collect_checksums(release)
    path = Path(__file__).resolve().parents[1] / "Formula" / "tuxedotask.rb"
    path.parent.mkdir(parents=True, exist_ok=True)
    output = render_formula(tag, checksums)
    if not path.exists() or path.read_text() != output:
        path.write_text(output)
        print(f"Updated {path.name} to {tag}")
    else:
        print(f"Formula already matches {tag}")


if __name__ == "__main__":
    main()
